#!/usr/bin/env node
/**
 * Regenerates src/components/mcp/config/presets.data.ts from data/extracted/*.json
 * (produced by scripts/extract-mcp.mjs). Run: node scripts/build-mcp-presets.cjs
 */
const fs = require("fs");
const path = require("path");

const DIR = path.resolve("data/extracted");
const load = (tab) => JSON.parse(fs.readFileSync(path.join(DIR, `${tab}.json`), "utf8"));
const CATEGORY_IDS = {
  Popular: "popular", "Paid Ads": "paid-ads", "Motion Design": "motion-design", Marketing: "marketing",
  Production: "production", UGC: "ugc", Faceless: "faceless", "For After Effects": "after-effects", "For Blender": "blender",
};
const TAB_IDS = ["chatgpt", "claude", "claude-code", "telegram", "cli", "other"];

const byTitle = (tab) => {
  const map = new Map();
  for (const [category, { cards }] of Object.entries(load(tab).categories)) {
    for (const card of cards) {
      const entry = map.get(card.title) ?? { card, categories: [] };
      entry.categories.push(CATEGORY_IDS[category]);
      map.set(card.title, entry);
    }
  }
  return map;
};

const tabs = Object.fromEntries(TAB_IDS.map((tab) => [tab, byTitle(tab)]));
const presets = [...tabs.chatgpt.values()].map(({ card, categories }) => {
  const claude = tabs.claude.get(card.title)?.card;
  // Plugin cards (Blender, After Effects, ...) have no prompt on the live page.
  const raw = claude?.promptDecoded ?? (card.promptDecoded ?? "").replace(/^@Higgsfield\n\n/, "");
  const body = raw.split("\n\nIf Higgsfield is not connected")[0].split("\n\nIf the Higgsfield plugin")[0];
  const [prompt, refBlock = ""] = body.split("\n\nReference media:\n");
  const references = [...refBlock.matchAll(/\]\((.+?)\)/g)].map((m) => m[1]);
  const slug = new URL(card.learnMoreHref).pathname.split("/").pop();
  const command = (prompt.match(/^\/([\w-]+)/) ?? [])[1] ?? "";
  return {
    id: slug,
    title: card.title,
    ...(card.isNew ? { isNew: true } : {}),
    description: card.description,
    command,
    tags: card.tags,
    categories: categories.filter((id) => id !== "popular"),
    popular: categories.includes("popular"),
    slug,
    prompt,
    references,
    media: card.video ? { kind: "video", src: card.video.src, poster: card.video.poster } : { kind: "image", src: card.images[0] },
    agents: TAB_IDS.filter((tab) => tabs[tab].has(card.title)),
  };
});

const out = `// Generated by scripts/build-mcp-presets.cjs from https://higgsfield.ai/mcp — do not edit by hand.
import type { PresetDefinition } from "../types";

export const PRESETS: PresetDefinition[] = ${JSON.stringify(presets, null, 2)};
`;
fs.writeFileSync(path.resolve("src/components/mcp/config/presets.data.ts"), out);
console.log(`presets: ${presets.length}`);
